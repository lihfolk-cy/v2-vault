#!/usr/bin/env python3
"""Install the LihFolk Codex skills into a separate Roblox project."""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SKILLS_SOURCE = ROOT / ".agents" / "skills"
AGENTS_SOURCE = ROOT / ".codex" / "agents"
HOOK_SOURCE = ROOT / ".codex" / "lihfolk" / "codex_post_tool.py"
HOOK_CONFIG_SOURCE = ROOT / ".codex" / "hooks.json"
CONFIG_MARKER = "LihFolk V2 Codex installer"
SKILL_MARKER = "<!-- Generated by scripts/sync_codex_skills.py; do not edit here. -->"
AGENT_MARKER = "Generated by LihFolk V2 Codex integration."
AGENTS_START = "<!-- lihfolk-codex:start -->"
AGENTS_END = "<!-- lihfolk-codex:end -->"
IGNORE_START = "# >>> LihFolk V2 Codex local configuration >>>"
IGNORE_END = "# <<< LihFolk V2 Codex local configuration <<<"


def normalize_vault_root(path: Path) -> Path:
    resolved = path.expanduser().resolve()
    if (resolved / "LihFolk Vault V2" / "_tools" / "vault.py").is_file():
        return resolved
    if (resolved / "_tools" / "vault.py").is_file() and (resolved.parent / "skills").is_dir():
        return resolved.parent
    raise ValueError(f"Not a LihFolk V2 repository or vault directory: {resolved}")


def managed_agents_block() -> str:
    return "\n".join(
        [
            AGENTS_START,
            "## Roblox development with LihFolk V2",
            "",
            "For Roblox work, use the installed LihFolk Codex skills. Use `lihfolk` to route non-trivial work and the matching specialist skill for the requested area.",
            "The vault root is configured in `.lihfolk-codex.json` (or `LIHFOLK_VAULT_ROOT`). Use `lihfolk-vault-search` to search summaries and retrieve exact sections; do not load the whole vault.",
            "Keep the game project and the LihFolk source repository separate. Read full `Common mistakes` and `Checklist` sections for player data, purchases, paid random items, security, and live-player changes.",
            "Use the project's native Codex agents for lookup or council review when delegation is available. Their instructions do not override the parent session's permissions.",
            AGENTS_END,
        ]
    )


def merge_agents_md(existing: str) -> str:
    block = managed_agents_block()
    if AGENTS_START in existing or AGENTS_END in existing:
        if existing.count(AGENTS_START) != 1 or existing.count(AGENTS_END) != 1:
            raise ValueError("AGENTS.md has an incomplete or duplicated LihFolk managed block")
        start = existing.index(AGENTS_START)
        end = existing.index(AGENTS_END) + len(AGENTS_END)
        if end < start:
            raise ValueError("AGENTS.md LihFolk markers are out of order")
        return existing[:start] + block + existing[end:]
    if not existing:
        return block + "\n"
    separator = "" if existing.endswith("\n") else "\n"
    return existing + separator + "\n" + block + "\n"


def merge_local_config(existing: str | None, vault_root: Path, python_executable: Path) -> str:
    data: dict[str, object] = {}
    if existing:
        try:
            loaded = json.loads(existing)
        except json.JSONDecodeError as exc:
            raise ValueError(f"Existing .lihfolk-codex.json is invalid JSON: {exc}") from exc
        if not isinstance(loaded, dict):
            raise ValueError("Existing .lihfolk-codex.json must contain a JSON object")
        if loaded.get("managed_by") not in (None, CONFIG_MARKER):
            raise ValueError("Existing .lihfolk-codex.json belongs to a different integration")
        data = loaded
    data.update(
        {
            "schema_version": 1,
            "integration": "LihFolk Vault V2 Codex",
            "managed_by": CONFIG_MARKER,
            "vault_root": str(vault_root),
            "python_executable": str(python_executable.resolve()),
        }
    )
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def merge_gitignore(existing: str | None, is_git_project: bool) -> str | None:
    if not is_git_project:
        return existing
    current = existing or ""
    managed = f"{IGNORE_START}\n.lihfolk-codex.json\n{IGNORE_END}"
    if IGNORE_START in current or IGNORE_END in current:
        if current.count(IGNORE_START) != 1 or current.count(IGNORE_END) != 1:
            raise ValueError(".gitignore has an incomplete or duplicated LihFolk managed block")
        start = current.index(IGNORE_START)
        end = current.index(IGNORE_END) + len(IGNORE_END)
        if end < start:
            raise ValueError(".gitignore LihFolk markers are out of order")
        updated = current[:start] + managed + current[end:]
    elif re.search(r"(?m)^\s*\.lihfolk-codex\.json\s*$", current):
        return existing
    else:
        separator = "" if not current or current.endswith("\n") else "\n"
        updated = current + separator + ("\n" if current and not current.endswith("\n\n") else "") + managed + "\n"
    return updated


def merge_hooks_json(existing: str | None) -> str:
    if existing:
        try:
            document = json.loads(existing)
        except json.JSONDecodeError as exc:
            raise ValueError(f"Existing .codex/hooks.json is invalid JSON: {exc}") from exc
        if not isinstance(document, dict):
            raise ValueError("Existing .codex/hooks.json must contain a JSON object")
    else:
        document = {}
    source_document = json.loads(HOOK_CONFIG_SOURCE.read_text(encoding="utf-8"))
    source_hooks = source_document.get("hooks", {})
    hooks = document.setdefault("hooks", {})
    if not isinstance(hooks, dict):
        raise ValueError("Existing .codex/hooks.json hooks value must be an object")
    for event_name, groups in source_hooks.items():
        current_groups = hooks.setdefault(event_name, [])
        if not isinstance(current_groups, list):
            raise ValueError(f"Existing .codex/hooks.json {event_name} value must be an array")
        for group in groups:
            command = group["hooks"][0]["command"]
            already_added = any(
                isinstance(existing_group, dict)
                and existing_group.get("matcher") == group.get("matcher")
                and any(
                    isinstance(handler, dict) and handler.get("command") == command
                    for handler in existing_group.get("hooks", [])
                )
                for existing_group in current_groups
            )
            if not already_added:
                current_groups.append(group)
    if not document.get("description"):
        document["description"] = source_document.get("description")
    return json.dumps(document, ensure_ascii=False, indent=2) + "\n"


def enable_hooks_feature(existing: str | None) -> str:
    text = existing or ""
    lines = text.splitlines()
    section_start = next((i for i, line in enumerate(lines) if re.match(r"^\s*\[features\]\s*(?:#.*)?$", line)), None)
    if section_start is None:
        if re.search(r"(?m)^\s*features\s*=", text):
            raise ValueError("Cannot merge codex_hooks into an inline features table; add it manually under [features]")
        addition = "[features]\ncodex_hooks = true\n"
        updated = text + ("\n" if text and not text.endswith("\n\n") else "") + addition
    else:
        section_end = len(lines)
        for i in range(section_start + 1, len(lines)):
            if re.match(r"^\s*\[\[?[^]]+\]\]?\s*(?:#.*)?$", lines[i]):
                section_end = i
                break
        feature_line = next(
            (i for i in range(section_start + 1, section_end) if re.match(r"^\s*codex_hooks\s*=", lines[i])),
            None,
        )
        if feature_line is None:
            lines.insert(section_end, "codex_hooks = true")
        else:
            old = lines[feature_line]
            comment = ""
            if "#" in old:
                comment = " #" + old.split("#", 1)[1]
            lines[feature_line] = re.sub(r"^(\s*codex_hooks\s*=\s*)[^#]+", r"\1true", old) + comment
        updated = "\n".join(lines) + ("\n" if text.endswith("\n") else "")

    try:
        import tomllib
    except ImportError:
        tomllib = None
    if tomllib is not None:
        parsed = tomllib.loads(updated)
        if parsed.get("features", {}).get("codex_hooks") is not True:
            raise ValueError("Could not enable codex_hooks in the project TOML")
    return updated


def is_managed_file(path: Path) -> bool:
    if not path.is_file():
        return False
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False
    return SKILL_MARKER in text or AGENT_MARKER in text


def write_atomically(path: Path, data: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", newline="\n", dir=path.parent, delete=False) as stream:
        stream.write(data)
        temp_path = Path(stream.name)
    try:
        temp_path.replace(path)
    finally:
        if temp_path.exists():
            temp_path.unlink()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Install LihFolk's native Codex skills into a Roblox project.")
    parser.add_argument("--project", required=True, type=Path, help="Existing Roblox project root")
    parser.add_argument("--vault-root", type=Path, default=ROOT, help="LihFolk V2 repository or vault path")
    parser.add_argument("--enable-hooks", action="store_true", help="Install the opt-in Codex PostToolUse Luau checker")
    args = parser.parse_args(argv)

    project = args.project.expanduser().resolve()
    if not project.is_dir():
        parser.error(f"Project root does not exist or is not a directory: {project}")
    try:
        vault_root = normalize_vault_root(args.vault_root)
    except ValueError as exc:
        parser.error(str(exc))
    if not SKILLS_SOURCE.is_dir() or not AGENTS_SOURCE.is_dir():
        parser.error("Native Codex artifacts are missing from this checkout; run scripts/sync_codex_skills.py first.")

    planned: dict[Path, str] = {}
    for source in sorted(SKILLS_SOURCE.rglob("*")):
        if source.is_file():
            relative = source.relative_to(SKILLS_SOURCE)
            planned[project / ".agents" / "skills" / relative] = source.read_text(encoding="utf-8")
    for source in sorted(AGENTS_SOURCE.glob("*.toml")):
        planned[project / ".codex" / "agents" / source.name] = source.read_text(encoding="utf-8")
    if args.enable_hooks:
        planned[project / ".codex" / "lihfolk" / "codex_post_tool.py"] = HOOK_SOURCE.read_text(encoding="utf-8")

    local_config_path = project / ".lihfolk-codex.json"
    agents_path = project / "AGENTS.md"
    gitignore_path = project / ".gitignore"
    codex_config_path = project / ".codex" / "config.toml"
    hooks_config_path = project / ".codex" / "hooks.json"

    existing_config = local_config_path.read_text(encoding="utf-8") if local_config_path.exists() else None
    planned[local_config_path] = merge_local_config(existing_config, vault_root, Path(sys.executable))
    planned[agents_path] = merge_agents_md(agents_path.read_text(encoding="utf-8") if agents_path.exists() else "")

    is_git_project = any((parent / ".git").exists() for parent in (project, *project.parents))
    merged_ignore = merge_gitignore(gitignore_path.read_text(encoding="utf-8") if gitignore_path.exists() else None, is_git_project)
    if merged_ignore is not None:
        planned[gitignore_path] = merged_ignore

    if args.enable_hooks:
        planned[hooks_config_path] = merge_hooks_json(hooks_config_path.read_text(encoding="utf-8") if hooks_config_path.exists() else None)
        planned[codex_config_path] = enable_hooks_feature(codex_config_path.read_text(encoding="utf-8") if codex_config_path.exists() else None)

    project_resolved = project.resolve()
    for path, content in planned.items():
        resolved = path.resolve(strict=False)
        try:
            resolved.relative_to(project_resolved)
        except ValueError as exc:
            raise ValueError(f"Refusing to write outside the project root: {path}") from exc
        for parent in path.parents:
            if parent == project.parent:
                break
            if parent.exists() and parent.is_symlink():
                raise ValueError(f"Refusing to follow a symlink while installing: {parent}")
        if path.is_symlink():
            raise ValueError(f"Refusing to replace a symlink: {path}")
        if path.exists() and path not in {local_config_path, agents_path, gitignore_path, hooks_config_path, codex_config_path}:
            current = path.read_text(encoding="utf-8") if path.is_file() else None
            if current != content and not is_managed_file(path):
                raise ValueError(f"Refusing to overwrite an existing file: {path}")

    for path, content in planned.items():
        if path.exists() and path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        write_atomically(path, content)

    skill_count = len(list(SKILLS_SOURCE.glob("*/SKILL.md")))
    agent_count = len(list(AGENTS_SOURCE.glob("*.toml")))
    print(f"Installed {skill_count} LihFolk Codex skills and {agent_count} custom agent profiles into {project}.")
    print(f"Configured the LihFolk source path in {local_config_path.name} and added the managed instructions block to AGENTS.md.")
    if args.enable_hooks:
        print("Installed the post-edit Luau hook. In Codex, review/trust it with /hooks before the first run.")
    else:
        print("Hooks were not enabled. Re-run with --enable-hooks to install the optional post-edit checker.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except ValueError as exc:
        print(f"LihFolk Codex installer: {exc}", file=os.sys.stderr)
        raise SystemExit(2)
