#!/usr/bin/env python3
"""Generate thin Codex skill entries that route to LihFolk's canonical guides.

The detailed guides remain in skills/ and commands/. Keeping the Codex entries
thin avoids duplicating the licensed knowledge and keeps initial skill context
small. Run this script after adding or renaming a source skill.
"""

from __future__ import annotations

import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE_SKILLS = ROOT / "skills"
OUTPUT_SKILLS = ROOT / ".agents" / "skills"
GENERATED_MARKER = "<!-- Generated by scripts/sync_codex_skills.py; do not edit here. -->"
ATTRIBUTION = "Adapted from LihFolk Vault V2 by LihFolk; licensed under [CC BY 4.0](https://creativecommons.org/licenses/by/4.0/). See the source [LICENSE.md](https://github.com/lihfolk-cy/v2-vault/blob/main/LICENSE.md)."

EXTRA_SKILLS = {
    "lihfolk-vault-search": {
        "description": (
            "Search LihFolk Vault V2 for Roblox notes, API references, and bug symptoms. "
            "Use when a Roblox task needs current limits, policy, debugging clues, or verified guidance."
        ),
        "source": None,
    },
    "roblox-project-audit": {
        "description": (
            "Review a Roblox project for Luau errors, insecure remotes, unsafe player data, "
            "purchase flaws, exploits, and performance risks. Use for project-wide audits."
        ),
        "source": "commands/audit.md",
    },
}

COMMAND_WORKFLOWS = {
    "lihfolk-assets": "commands/assets.md",
    "council-method": "commands/council.md",
    "quality-score": "commands/learn.md",
    "roblox-system-builder": "commands/new-system.md",
    "roblox-trend-game": "commands/trend-game.md",
}


def parse_source_skill(path: Path) -> tuple[str, str]:
    text = path.read_text(encoding="utf-8")
    match = re.search(r"(?ms)^---\s*\n(.*?)\n---\s*\n", text)
    if not match:
        raise ValueError(f"Missing YAML frontmatter: {path}")
    frontmatter = match.group(1)
    name_match = re.search(r"(?m)^name:\s*([a-z0-9][a-z0-9-]*)\s*$", frontmatter)
    description_match = re.search(r"(?m)^description:\s*'(.*)'\s*$", frontmatter)
    if not name_match or not description_match:
        raise ValueError(f"Expected name and single-quoted description: {path}")
    description = description_match.group(1).replace("''", "'")
    return name_match.group(1), description


def render_skill(name: str, description: str, source: str | None) -> str:
    quoted_description = json.dumps(description, ensure_ascii=False)
    lines = [
        "---",
        f"name: {name}",
        f"description: {quoted_description}",
        "---",
        "",
        GENERATED_MARKER,
        "",
        ATTRIBUTION,
        "",
        "# LihFolk V2 for Codex",
        "",
        "This is a small Codex discovery entry. The full LihFolk workflow stays in the canonical source files so the vault and skill content are not duplicated.",
        "",
        "## Resolve the LihFolk source",
        "",
        "1. In a separate Roblox project, read `.lihfolk-codex.json` from the project root and use its `vault_root` value. `LIHFOLK_VAULT_ROOT` is a supported override.",
        "2. When Codex is open on the LihFolk repository itself, find the repository root containing both `skills/` and `LihFolk Vault V2/_tools/vault.py`.",
        "3. If neither location exists, explain that the LihFolk source path is missing. Do not scan drives or load the whole vault.",
        "4. Keep the game-project root separate from `vault_root`. Use quoted paths whenever invoking a shell command; both paths may contain spaces.",
        "",
        "## Follow the canonical workflow",
        "",
    ]

    if source is None:
        lines.extend(
            [
                "Use this skill when a Roblox answer depends on LihFolk's knowledge base.",
                "",
                "1. Run the packaged helper at `.agents/skills/lihfolk-vault-search/scripts/vault_search.py` with the user's task or symptom as one quoted argument. Read `.lihfolk-codex.json` for the configured vault and Python executable. On Windows, use `py -3` when available, or invoke the configured `python_executable` directly in PowerShell (`& '<python_executable>' '<helper path>' '<query>'`) if the launcher is missing. On macOS/Linux, use `python3` or `python`.",
                "2. Use `--read`, `--sections`, or `--api` through the same helper to retrieve only the exact section or API check needed.",
                "3. Read the full `Common mistakes` and `Checklist` sections for player data, purchases, paid random items, security, and anything shipping to live players. A TL;DR is only a pointer.",
                "4. Cite the note titles you used. Prefer `Roblox docs` and `Measured` claims; verify `Unverified` claims. Check current Roblox documentation for changed limits, APIs, or policy.",
                "5. If Python or the source files are missing, report the exact path or launcher problem and use `INDEX_SLIM.md` or `SYMPTOMS.md` as a limited fallback.",
                "",
                "The helper requires Python 3 and the source repository. It uses argument arrays rather than shell interpolation, so paths with spaces are supported.",
            ]
        )
    else:
        if source.startswith("commands/") and (SOURCE_SKILLS / name / "SKILL.md").is_file():
            lines.extend(
                [
                    f"Read the canonical command workflow at `<vault_root>/{source}` and the specialist skill at `<vault_root>/skills/{name}/SKILL.md` before doing this work.",
                    f"Open supporting files beside `<vault_root>/skills/{name}/SKILL.md` only when either canonical guide calls for them.",
                    "Replace any source `$ARGUMENTS` placeholder with the user's request and apply the workflow to the current Roblox project.",
                    "",
                ]
            )
        else:
            lines.extend(
                [
                    f"Read the full canonical workflow at `<vault_root>/{source}` before doing this work.",
                    f"For specialist skills, also open supporting files beside `<vault_root>/skills/{name}/SKILL.md` only when the canonical guide calls for them.",
                    "Treat that source file as the detailed workflow and apply it to the current Roblox project.",
                    "",
                ]
            )

    lines.extend(
        [
            "## Codex compatibility",
            "",
            "- Treat the user's current request as the argument to any source command that contains `$ARGUMENTS`; do not execute Claude slash commands.",
            "- Resolve `CLAUDE_PLUGIN_ROOT` in source instructions as `vault_root` from `.lihfolk-codex.json` or `LIHFOLK_VAULT_ROOT`.",
            "- Replace Claude-specific tool names with the available Codex file and shell tools. Use the profiles under `.codex/agents/` only when Codex delegation is available; otherwise complete the closest safe workflow directly and state the limit.",
            "- Keep all work on the user's game project unless the user asks to edit the LihFolk source repository.",
        ]
    )
    return "\n".join(lines) + "\n"


def main() -> int:
    sources = sorted(SOURCE_SKILLS.rglob("SKILL.md"))
    generated: dict[str, tuple[str, str | None]] = {}
    for path in sources:
        name, description = parse_source_skill(path)
        if name in generated:
            raise ValueError(f"Duplicate source skill name: {name}")
        generated[name] = (description, COMMAND_WORKFLOWS.get(name, f"skills/{name}/SKILL.md"))

    for name, details in EXTRA_SKILLS.items():
        if name in generated:
            raise ValueError(f"Extra skill shadows source skill: {name}")
        generated[name] = (details["description"], details["source"])

    for name, (description, source) in sorted(generated.items()):
        destination = OUTPUT_SKILLS / name / "SKILL.md"
        if destination.exists():
            previous = destination.read_text(encoding="utf-8")
            if GENERATED_MARKER not in previous:
                raise RuntimeError(f"Refusing to overwrite a non-generated skill: {destination}")
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(render_skill(name, description, source), encoding="utf-8", newline="\n")

    print(f"Generated {len(generated)} Codex skill entries in {OUTPUT_SKILLS.relative_to(ROOT)}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
