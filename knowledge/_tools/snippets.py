"""Compile every ```lua / ```luau code block in the vault with the official Luau compiler.

Usage (needs luau-compile from https://github.com/luau-lang/luau/releases; set LUAU_COMPILE or put it on PATH):
    python knowledge/_tools/snippets.py              # compile all, print summary, write _tools/reports/snippets.md
    python knowledge/_tools/snippets.py --strict     # exit 1 on any failure not in snippet_allow.txt (CI)

A block that is a deliberate fragment (pseudo-code, a "before" example, a partial table) is listed in
snippet_allow.txt by note path and block hash, with a reason. Syntax only: API names are api_check.py's job.
"""
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile

TOOLS = os.path.dirname(os.path.abspath(__file__))
KB = os.path.dirname(TOOLS)
ALLOW = os.path.join(TOOLS, "snippet_allow.txt")
REPORT = os.path.join(TOOLS, "reports", "snippets.md")
COMPILER = os.environ.get("LUAU_COMPILE") or shutil.which("luau-compile") or "luau-compile"
BLOCK = re.compile(r"^```(lua|luau)[^\n]*\n(.*?)^```", re.S | re.M | re.I)


def blocks():
    for root, dirs, fs in os.walk(KB):
        dirs[:] = sorted(d for d in dirs if not d.startswith((".", "_")))
        for f in sorted(fs):
            if not f.endswith(".md"):
                continue
            path = os.path.join(root, f)
            rel = os.path.relpath(path, KB).replace(os.sep, "/")
            text = open(path, encoding="utf-8").read()
            for m in BLOCK.finditer(text):
                code = m.group(2)
                h = hashlib.sha1(code.strip().encode()).hexdigest()[:10]
                yield rel, text.count("\n", 0, m.start(2)) + 1, h, code


def main():
    strict = "--strict" in sys.argv
    allow = {}
    if os.path.exists(ALLOW):
        for line in open(ALLOW, encoding="utf-8"):
            body = line.split("#", 1)[0].strip()
            if body:
                p, h = (x.strip() for x in body.split("|"))
                allow[(p, h)] = line.split("#", 1)[1].strip() if "#" in line else ""
    items = list(blocks())
    tmp = tempfile.mkdtemp(prefix="vault_snippets_")
    files = []
    for i, (rel, line, h, code) in enumerate(items):
        fp = os.path.join(tmp, f"{i:05d}.luau")
        with open(fp, "w", encoding="utf-8") as f:
            f.write(code)
        files.append(fp)
    errors = {}
    try:
        for k in range(0, len(files), 200):
            r = subprocess.run([COMPILER, "--null"] + files[k:k + 200], capture_output=True, text=True)
            for m in re.finditer(r"(\d{5})\.luau\((\d+),\d+\): (.*)", r.stdout + r.stderr):
                errors.setdefault(int(m.group(1)), (int(m.group(2)), m.group(3).strip()))
    except FileNotFoundError:
        sys.exit(f"luau-compile not found ({COMPILER}); set LUAU_COMPILE")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    failed, allowed = [], 0
    for i, (ln, msg) in sorted(errors.items()):
        rel, line, h, _ = items[i]
        if (rel, h) in allow:
            allowed += 1
            continue
        failed.append((rel, line + ln - 1, h, msg))
    ok = len(items) - len(errors)
    out = ["# Snippet compile report", "",
           f"Generated by `_tools/snippets.py` with `luau-compile --null`: {len(items)} Luau blocks, {ok} compile, "
           f"{allowed} known fragments (`snippet_allow.txt`), {len(failed)} failing.", "",
           "| Note | Line | Block hash | Error |", "|---|---:|---|---|"]
    out += [f"| {r} | {l} | `{h}` | {m.replace('|', '/')} |" for r, l, h, m in failed]
    os.makedirs(os.path.dirname(REPORT), exist_ok=True)
    with open(REPORT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(out[2])
    for r, l, h, m in failed[:80]:
        print(f"  {r}:{l}  [{h}]  {m}")
    if strict and failed:
        sys.exit(1)


if __name__ == "__main__":
    main()
